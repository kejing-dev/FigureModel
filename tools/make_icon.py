"""Figure Model icon (design `appIcon`): one set of shapes drawn three ways, so they always match:
the adaptive-icon foreground vector (`res/drawable/ic_launcher_foreground.xml`), the legacy launcher PNG and
the 512 export for the factory gallery.

    python tools/make_icon.py <export-512.png>

Deep beech brown tile #8A5A2B, a white flat line mannequin seen from the front (round head, chest and pelvis
ovals, straight limbs, eight small joint dots; right arm raised, left hand on the hip, contrapposto legs) and a
thin 270 degree timer arc at its upper right. Coordinates are the vector's 108-unit viewport (safe zone 21..87).
"""
import os
import sys

from PIL import Image, ImageDraw

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
RES = os.path.join(ROOT, "app", "src", "main", "res")
BROWN = (0x8A, 0x5A, 0x2B, 255)
WHITE = (255, 255, 255, 255)

LIMB_W = 3.4
LIMBS = [
    [(41.5, 39), (37, 30), (35, 21)],  # right arm raised (the figure's right = viewer's left)
    [(54.5, 39), (62, 47.5), (54.5, 55)],  # left hand on the hip
    [(45, 59), (43, 70.5), (42, 82)],  # right leg, straight (weight)
    [(51, 59), (55.5, 70), (54, 81.5)],  # left leg, relaxed
    [(48, 51.5), (48, 53.5)],  # waist
]
HEAD = (48, 29.5, 5.2)
CHEST = (48, 44, 6.6, 7.2)
PELVIS = (48, 57, 5.6, 3.6)
JOINTS = [(41.5, 39), (54.5, 39), (37, 30), (62, 47.5), (45, 59), (51, 59), (43, 70.5), (55.5, 70)]
JOINT_R = 2.4
ARC = (72, 31, 8.5, 2.6)  # centre x, y, radius, stroke: 270 degrees clockwise from the top


def vector():
    def stroke(d, w):
        return (
            "    <path\n"
            f'        android:pathData="{d}"\n'
            '        android:strokeColor="#FFFFFFFF"\n'
            f'        android:strokeWidth="{w}"\n'
            '        android:strokeLineCap="round"\n'
            '        android:strokeLineJoin="round"\n'
            '        android:fillColor="#00000000" />\n'
        )

    def fill(d):
        return f'    <path\n        android:pathData="{d}"\n        android:fillColor="#FFFFFFFF" />\n'

    def ellipse(cx, cy, rx, ry):
        return f"M{cx - rx},{cy}a{rx},{ry} 0,1 1,{2 * rx},0a{rx},{ry} 0,1 1,{-2 * rx},0z"

    out = [
        '<?xml version="1.0" encoding="utf-8"?>\n',
        "<!-- Figure Model: white line mannequin with joint dots and a 270 degree timer arc (design appIcon); "
        "generated by tools/make_icon.py -->\n",
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n',
    ]
    for pts in LIMBS:
        out.append(stroke("M" + " L".join(f"{x},{y}" for x, y in pts), LIMB_W))
    out.append(fill(ellipse(HEAD[0], HEAD[1], HEAD[2], HEAD[2])))
    out.append(fill(ellipse(*CHEST)))
    out.append(fill(ellipse(*PELVIS)))
    for x, y in JOINTS:
        out.append(fill(ellipse(x, y, JOINT_R, JOINT_R)))
    cx, cy, r, w = ARC
    out.append(stroke(f"M{cx},{cy - r} A{r},{r} 0 1,1 {cx - r},{cy}", w))
    out.append("</vector>\n")
    return "".join(out)


def draw(size, rounded):
    S = 1080
    K = S / 108.0
    im = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    if rounded:
        d.rounded_rectangle((0, 0, S, S), radius=int(S * 0.22), fill=BROWN)
    else:
        d.rectangle((0, 0, S, S), fill=BROWN)

    def dot(x, y, r):
        d.ellipse(((x - r) * K, (y - r) * K, (x + r) * K, (y + r) * K), fill=WHITE)

    for pts in LIMBS:
        d.line([(x * K, y * K) for x, y in pts], fill=WHITE, width=int(LIMB_W * K), joint="curve")
        for x, y in pts:
            dot(x, y, LIMB_W / 2)
    dot(HEAD[0], HEAD[1], HEAD[2])
    for cx, cy, rx, ry in (CHEST, PELVIS):
        d.ellipse(((cx - rx) * K, (cy - ry) * K, (cx + rx) * K, (cy + ry) * K), fill=WHITE)
    for x, y in JOINTS:
        dot(x, y, JOINT_R)
    cx, cy, r, w = ARC
    # PIL angles: 0 = 3 o'clock, clockwise; from the top (270) round to the left (180)
    d.arc(((cx - r - w / 2) * K, (cy - r - w / 2) * K, (cx + r + w / 2) * K, (cy + r + w / 2) * K), start=270, end=180, fill=WHITE, width=int(w * K))
    for a in ((cx, cy - r), (cx - r, cy)):
        dot(a[0], a[1], w / 2)
    return im.resize((size, size), Image.LANCZOS)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "icon-512.png")
    with open(os.path.join(RES, "drawable", "ic_launcher_foreground.xml"), "w", encoding="utf8", newline="\n") as f:
        f.write(vector())
    draw(512, rounded=True).save(out)
    draw(192, rounded=False).save(os.path.join(RES, "mipmap-xxxhdpi", "ic_launcher.png"))
    print("wrote", out)


if __name__ == "__main__":
    main()
